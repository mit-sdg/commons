export function commonsHttpPolicy(publicOrigin: string) {
  return httpPolicy({
    publicOrigin,
    basePath: "/api",
    publicErrors: commonsPublicErrors,
    cookies: {
      session: {
        name: "commons-session",
        input: "session",
        issue: [{ path: "/auth/login", value: "session", expires: "expiresAt" }],
        clear: ["/auth/logout", "/auth/changePassword"],
      },
    },
  });
}
